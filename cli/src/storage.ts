import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { createArchitectureSvg, createEntryPointsSvg } from "./diagrams.js";
import type { AnalyzeSuccessResponse, StoredProject } from "./types.js";

export const outputDirectoryName = ".repomd";

function reportMarkdown(data: AnalyzeSuccessResponse): string {
  const { analysis } = data;
  const secondary = analysis.entryPoints.secondary
    .map((item) => `- \`${item.file}\` — ${item.description}`)
    .join("\n");
  const flow = analysis.executionFlow
    .map((item) => `${item.step}. **${item.layer}** — \`${item.file}\`: ${item.description}`)
    .join("\n");

  return `# ${data.repoFullName}

Generated by RepoMD.

## Summary

${analysis.repoSummary.description}

**Architecture:** ${analysis.repoSummary.architectureStyle}

## Primary entry point

\`${analysis.entryPoints.primary.file}\` — ${analysis.entryPoints.primary.description}

## Secondary entry points

${secondary || "None detected."}

## Execution flow

${flow || "No execution flow detected."}
`;
}

export async function saveProject(
  cwd: string,
  repositoryUrl: string,
  analyzedCommit: string | undefined,
  data: AnalyzeSuccessResponse
): Promise<StoredProject> {
  const directory = path.join(cwd, outputDirectoryName);
  await mkdir(directory, { recursive: true });
  const project: StoredProject = {
    version: 1,
    repositoryUrl,
    analyzedCommit,
    generatedAt: new Date().toISOString(),
    data,
  };

  await Promise.all([
    writeFile(path.join(directory, "analysis.json"), `${JSON.stringify(project, null, 2)}\n`, "utf8"),
    writeFile(path.join(directory, "report.md"), reportMarkdown(data), "utf8"),
    writeFile(path.join(directory, "architecture.svg"), createArchitectureSvg(data.repoFullName, data.analysis), "utf8"),
    writeFile(path.join(directory, "entry-points.svg"), createEntryPointsSvg(data.repoFullName, data.analysis), "utf8"),
  ]);

  return project;
}

export async function loadProject(cwd: string): Promise<StoredProject | null> {
  try {
    const raw = await readFile(path.join(cwd, outputDirectoryName, "analysis.json"), "utf8");
    const value = JSON.parse(raw) as StoredProject;
    if (value.version !== 1 || !value.data?.ok || !value.data.analysis) return null;
    return value;
  } catch {
    return null;
  }
}

export async function refreshDiagrams(cwd: string, project: StoredProject): Promise<void> {
  const directory = path.join(cwd, outputDirectoryName);
  await mkdir(directory, { recursive: true });
  await Promise.all([
    writeFile(path.join(directory, "architecture.svg"), createArchitectureSvg(project.data.repoFullName, project.data.analysis), "utf8"),
    writeFile(path.join(directory, "entry-points.svg"), createEntryPointsSvg(project.data.repoFullName, project.data.analysis), "utf8"),
  ]);
}
