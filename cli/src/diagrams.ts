import type { AnalysisResult } from "./types.js";

function escapeXml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function shorten(value: string, length: number): string {
  return value.length > length ? `${value.slice(0, length - 1)}…` : value;
}

function svgShell(width: number, height: number, title: string, content: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title desc">
  <title id="title">${escapeXml(title)}</title>
  <desc id="desc">Generated by RepoMD</desc>
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#07110f"/><stop offset="1" stop-color="#0d1916"/></linearGradient>
    <marker id="arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" orient="auto"><path d="M0,0 L0,6 L9,3 z" fill="#20c997"/></marker>
    <filter id="glow"><feGaussianBlur stdDeviation="2" result="blur"/><feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge></filter>
  </defs>
  <rect width="100%" height="100%" rx="24" fill="url(#bg)"/>
  <text x="48" y="58" fill="#20c997" font-family="ui-monospace,monospace" font-size="30" font-weight="700">RepoMD</text>
  <text x="48" y="88" fill="#8aa39b" font-family="ui-monospace,monospace" font-size="15">${escapeXml(title)}</text>
  ${content}
</svg>`;
}

export function createArchitectureSvg(repoName: string, analysis: AnalysisResult): string {
  const steps = analysis.executionFlow.slice(0, 10);
  const width = 1200;
  const startY = 130;
  const cardHeight = 92;
  const gap = 38;
  const height = Math.max(420, startY + steps.length * (cardHeight + gap) + 40);
  const cards = steps.map((step, index) => {
    const y = startY + index * (cardHeight + gap);
    const arrow = index === steps.length - 1
      ? ""
      : `<path d="M600 ${y + cardHeight} L600 ${y + cardHeight + gap - 9}" stroke="#20c997" stroke-width="3" marker-end="url(#arrow)" filter="url(#glow)"/>`;
    return `${arrow}
    <rect x="120" y="${y}" width="960" height="${cardHeight}" rx="16" fill="#10251f" stroke="#1f6f5a"/>
    <circle cx="164" cy="${y + 46}" r="22" fill="#20c997"/>
    <text x="164" y="${y + 53}" text-anchor="middle" fill="#03110d" font-family="ui-monospace,monospace" font-size="18" font-weight="700">${step.step}</text>
    <text x="205" y="${y + 34}" fill="#e8fff7" font-family="ui-monospace,monospace" font-size="19" font-weight="700">${escapeXml(shorten(step.layer, 65))}</text>
    <text x="205" y="${y + 61}" fill="#69dbb8" font-family="ui-monospace,monospace" font-size="15">${escapeXml(shorten(step.file, 94))}</text>
    <text x="205" y="${y + 81}" fill="#9bb8ae" font-family="ui-monospace,monospace" font-size="13">${escapeXml(shorten(step.description, 115))}</text>`;
  }).join("\n");
  return svgShell(width, height, `${repoName} · Architecture`, cards || '<text x="48" y="150" fill="#9bb8ae">No execution flow was detected.</text>');
}

export function createEntryPointsSvg(repoName: string, analysis: AnalysisResult): string {
  const primary = analysis.entryPoints.primary;
  const secondary = analysis.entryPoints.secondary.slice(0, 8);
  const items = [{ file: primary.file, description: primary.description, primary: true }, ...secondary.map((item) => ({ ...item, primary: false }))];
  const width = 1200;
  const height = Math.max(380, 140 + items.length * 105);
  const content = items.map((item, index) => {
    const y = 125 + index * 105;
    const color = item.primary ? "#20c997" : "#4dabf7";
    return `<rect x="90" y="${y}" width="1020" height="78" rx="14" fill="#10211d" stroke="${color}"/>
    <text x="122" y="${y + 31}" fill="${color}" font-family="ui-monospace,monospace" font-size="14" font-weight="700">${item.primary ? "PRIMARY" : "SECONDARY"}</text>
    <text x="250" y="${y + 31}" fill="#e8fff7" font-family="ui-monospace,monospace" font-size="18" font-weight="700">${escapeXml(shorten(item.file, 80))}</text>
    <text x="122" y="${y + 58}" fill="#9bb8ae" font-family="ui-monospace,monospace" font-size="14">${escapeXml(shorten(item.description, 120))}</text>`;
  }).join("\n");
  return svgShell(width, height, `${repoName} · Entry Points`, content);
}
