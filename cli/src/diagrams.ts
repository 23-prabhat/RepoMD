import type { AnalysisResult } from "./types.js";

function escapeXml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function shorten(value: string, length: number): string {
  return value.length > length ? `${value.slice(0, length - 1)}…` : value;
}

function wrapText(value: string, maxCharacters: number, maxLines = 2): string[] {
  const words = value.trim().split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = "";

  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (next.length <= maxCharacters) {
      current = next;
      continue;
    }
    if (current) lines.push(current);
    current = word;
    if (lines.length === maxLines - 1) break;
  }

  if (current && lines.length < maxLines) lines.push(current);
  if (lines.join(" ").length < value.trim().length && lines.length > 0) {
    lines[lines.length - 1] = shorten(lines[lines.length - 1], Math.max(4, maxCharacters - 1));
  }
  return lines;
}

function textLines(lines: string[], x: number, y: number, lineHeight: number, attributes: string): string {
  return lines
    .map((line, index) => `<text x="${x}" y="${y + index * lineHeight}" ${attributes}>${escapeXml(line)}</text>`)
    .join("\n");
}

function svgShell(width: number, height: number, title: string, content: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title desc">
  <title id="title">${escapeXml(title)}</title>
  <desc id="desc">Layered repository architecture generated by RepoMD</desc>
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#06100e"/><stop offset="0.55" stop-color="#0a1714"/><stop offset="1" stop-color="#0c1320"/></linearGradient>
    <linearGradient id="card" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#10251f"/><stop offset="1" stop-color="#101d22"/></linearGradient>
    <marker id="flow-arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" orient="auto"><path d="M0,0 L0,6 L9,3 z" fill="#20c997"/></marker>
    <marker id="dependency-arrow" markerWidth="10" markerHeight="10" refX="8" refY="3" orient="auto"><path d="M0,0 L0,6 L9,3 z" fill="#4dabf7"/></marker>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="6" stdDeviation="8" flood-color="#000" flood-opacity="0.28"/></filter>
  </defs>
  <rect width="100%" height="100%" rx="24" fill="url(#bg)"/>
  <text x="56" y="55" fill="#20c997" font-family="ui-monospace,monospace" font-size="28" font-weight="700">RepoMD</text>
  <text x="56" y="84" fill="#8aa39b" font-family="ui-monospace,monospace" font-size="14">${escapeXml(title)}</text>
  ${content}
</svg>`;
}

type ArchitectureItem = {
  file: string;
  layer: string;
  description: string;
  step?: number;
  category?: string;
};

type CardPosition = { x: number; y: number; width: number; height: number };

const LAYER_COLORS = ["#ff6b9d", "#4dabf7", "#20c997", "#bf7fff", "#ffb84d", "#38d9a9"];

function supportLayer(): string {
  // Category remains visible on each card. Keeping non-flow files in one lane
  // avoids a very tall diagram made of one-card layers.
  return "Supporting components";
}

function architectureGroups(analysis: AnalysisResult): Map<string, ArchitectureItem[]> {
  const groups = new Map<string, ArchitectureItem[]>();
  const includedFiles = new Set<string>();
  const sortedSteps = [...analysis.executionFlow].sort((a, b) => a.step - b.step).slice(0, 12);

  for (const step of sortedSteps) {
    if (includedFiles.has(step.file)) continue;
    includedFiles.add(step.file);
    if (!groups.has(step.layer)) groups.set(step.layer, []);
    const critical = analysis.criticalFiles.find((file) => file.file === step.file);
    groups.get(step.layer)!.push({
      file: step.file,
      layer: step.layer,
      description: step.description,
      step: step.step,
      category: critical?.category,
    });
  }

  for (const critical of analysis.criticalFiles.slice(0, 12)) {
    if (includedFiles.has(critical.file)) continue;
    includedFiles.add(critical.file);
    const layer = supportLayer();
    if (!groups.has(layer)) groups.set(layer, []);
    groups.get(layer)!.push({
      file: critical.file,
      layer,
      description: critical.reason,
      category: critical.category,
    });
  }

  return groups;
}

export function createArchitectureSvg(repoName: string, analysis: AnalysisResult): string {
  const groups = architectureGroups(analysis);
  const width = 1440;
  const marginX = 56;
  const contentWidth = width - marginX * 2;
  const columns = 4;
  const columnGap = 22;
  const cardWidth = Math.floor((contentWidth - columnGap * (columns - 1)) / columns);
  const cardHeight = 120;
  const rowGap = 18;
  const layerHeaderHeight = 48;
  const layerGap = 30;
  const startY = 178;
  const positions = new Map<string, CardPosition>();
  const sections: string[] = [];
  let cursorY = startY;

  [...groups.entries()].forEach(([layer, items], layerIndex) => {
    const rows = Math.max(1, Math.ceil(items.length / columns));
    const sectionHeight = layerHeaderHeight + rows * cardHeight + (rows - 1) * rowGap + 24;
    const color = LAYER_COLORS[layerIndex % LAYER_COLORS.length];

    sections.push(`<rect x="${marginX}" y="${cursorY}" width="${contentWidth}" height="${sectionHeight}" rx="18" fill="#ffffff" fill-opacity="0.025" stroke="${color}" stroke-opacity="0.25"/>
    <rect x="${marginX}" y="${cursorY}" width="5" height="${sectionHeight}" rx="3" fill="${color}"/>
    <text x="${marginX + 22}" y="${cursorY + 30}" fill="${color}" font-family="ui-monospace,monospace" font-size="14" font-weight="700" letter-spacing="1.2">${escapeXml(layer.toUpperCase())}</text>
    <text x="${width - marginX - 22}" y="${cursorY + 30}" text-anchor="end" fill="#6f8f85" font-family="ui-monospace,monospace" font-size="12">${items.length} component${items.length === 1 ? "" : "s"}</text>`);

    items.forEach((item, itemIndex) => {
      const column = itemIndex % columns;
      const row = Math.floor(itemIndex / columns);
      const x = marginX + 18 + column * (cardWidth + columnGap);
      const y = cursorY + layerHeaderHeight + row * (cardHeight + rowGap);
      const actualWidth = cardWidth - (column === columns - 1 ? 18 : 0);
      positions.set(item.file, { x, y, width: actualWidth, height: cardHeight });
      const fileName = item.file.split("/").pop() || item.file;
      const path = item.file.includes("/") ? item.file.slice(0, item.file.lastIndexOf("/")) : "repository root";
      const description = wrapText(item.description, 40, 2);
      const badge = item.category
        ? `<rect x="${x + actualWidth - 94}" y="${y + 15}" width="78" height="20" rx="10" fill="${color}" fill-opacity="0.12" stroke="${color}" stroke-opacity="0.45"/><text x="${x + actualWidth - 55}" y="${y + 29}" text-anchor="middle" fill="${color}" font-family="ui-monospace,monospace" font-size="9" font-weight="700">${escapeXml(shorten(item.category.toUpperCase(), 12))}</text>`
        : "";
      const step = item.step === undefined
        ? `<circle cx="${x + 25}" cy="${y + 25}" r="10" fill="${color}" fill-opacity="0.22" stroke="${color}"/><circle cx="${x + 25}" cy="${y + 25}" r="3" fill="${color}"/>`
        : `<circle cx="${x + 25}" cy="${y + 25}" r="13" fill="${color}"/><text x="${x + 25}" y="${y + 30}" text-anchor="middle" fill="#07110f" font-family="ui-monospace,monospace" font-size="11" font-weight="800">${item.step}</text>`;

      sections.push(`<g filter="url(#shadow)"><rect x="${x}" y="${y}" width="${actualWidth}" height="${cardHeight}" rx="13" fill="url(#card)" stroke="${color}" stroke-opacity="0.42"/></g>
      ${step}${badge}
      <text x="${x + 47}" y="${y + 29}" fill="#e8fff7" font-family="ui-monospace,monospace" font-size="14" font-weight="700">${escapeXml(shorten(fileName, 27))}</text>
      <text x="${x + 17}" y="${y + 55}" fill="${color}" fill-opacity="0.88" font-family="ui-monospace,monospace" font-size="10">${escapeXml(shorten(path, 47))}</text>
      ${textLines(description, x + 17, y + 80, 17, 'fill="#9bb8ae" font-family="ui-sans-serif,system-ui,sans-serif" font-size="11.5"')}`);
    });

    cursorY += sectionHeight + layerGap;
  });

  const sortedSteps = [...analysis.executionFlow].sort((a, b) => a.step - b.step).slice(0, 12);
  const flowConnections: string[] = [];
  const flowPairs = new Set<string>();
  for (let index = 0; index < sortedSteps.length - 1; index++) {
    const from = sortedSteps[index];
    const to = sortedSteps[index + 1];
    if (from.file === to.file) continue;
    const source = positions.get(from.file);
    const target = positions.get(to.file);
    if (!source || !target) continue;
    flowPairs.add(`${from.file}||${to.file}`);
    const sx = source.x + source.width / 2;
    const sy = source.y + source.height;
    const tx = target.x + target.width / 2;
    const ty = target.y;
    const middle = sy + (ty - sy) / 2;
    flowConnections.push(`<path d="M${sx} ${sy} C${sx} ${middle}, ${tx} ${middle}, ${tx} ${ty - 7}" fill="none" stroke="#20c997" stroke-width="2.5" stroke-opacity="0.85" marker-end="url(#flow-arrow)"/>`);
  }

  const dependencyConnections: string[] = [];
  for (const dependency of analysis.dependencyMap) {
    if (dependencyConnections.length >= 10) break;
    if (flowPairs.has(`${dependency.from}||${dependency.to}`)) continue;
    const source = positions.get(dependency.from);
    const target = positions.get(dependency.to);
    if (!source || !target) continue;
    const sx = source.x + source.width;
    const sy = source.y + source.height / 2;
    const tx = target.x;
    const ty = target.y + target.height / 2;
    dependencyConnections.push(`<path d="M${sx} ${sy} C${sx + 34} ${sy}, ${tx - 34} ${ty}, ${tx - 7} ${ty}" fill="none" stroke="#4dabf7" stroke-width="1.5" stroke-dasharray="6 5" stroke-opacity="0.58" marker-end="url(#dependency-arrow)"/>`);
  }

  const metadata = `<rect x="56" y="110" width="${contentWidth}" height="48" rx="12" fill="#ffffff" fill-opacity="0.035" stroke="#ffffff" stroke-opacity="0.08"/>
  <text x="76" y="140" fill="#dff8ef" font-family="ui-monospace,monospace" font-size="13" font-weight="700">${escapeXml(shorten(analysis.repoSummary.architectureStyle, 80))}</text>
  <text x="${width - 430}" y="140" fill="#8aa39b" font-family="ui-monospace,monospace" font-size="11">${groups.size} LAYERS · ${positions.size} COMPONENTS · ${flowConnections.length} FLOW LINKS</text>
  <line x1="56" y1="${cursorY - 10}" x2="${width - 56}" y2="${cursorY - 10}" stroke="#ffffff" stroke-opacity="0.08"/>
  <path d="M72 ${cursorY + 18} h34" stroke="#20c997" stroke-width="3" marker-end="url(#flow-arrow)"/><text x="118" y="${cursorY + 22}" fill="#8aa39b" font-family="ui-monospace,monospace" font-size="11">EXECUTION FLOW</text>
  <path d="M272 ${cursorY + 18} h34" stroke="#4dabf7" stroke-width="2" stroke-dasharray="6 5" marker-end="url(#dependency-arrow)"/><text x="318" y="${cursorY + 22}" fill="#8aa39b" font-family="ui-monospace,monospace" font-size="11">DEPENDENCY</text>`;

  const empty = '<text x="56" y="215" fill="#9bb8ae" font-family="ui-monospace,monospace" font-size="15">No architecture components were detected.</text>';
  const content = groups.size === 0
    ? metadata + empty
    : `${metadata}<g>${flowConnections.join("\n")}${dependencyConnections.join("\n")}</g>${sections.join("\n")}`;
  return svgShell(width, Math.max(460, cursorY + 58), `${repoName} · Architecture`, content);
}

export function createEntryPointsSvg(repoName: string, analysis: AnalysisResult): string {
  const primary = analysis.entryPoints.primary;
  const secondary = analysis.entryPoints.secondary.slice(0, 8);
  const items = [{ file: primary.file, description: primary.description, primary: true }, ...secondary.map((item) => ({ ...item, primary: false }))];
  const width = 1200;
  const height = Math.max(420, 176 + items.length * 112 + Math.min(primary.executionFlow.length, 8) * 28);
  const cards = items.map((item, index) => {
    const y = 125 + index * 112;
    const color = item.primary ? "#20c997" : "#4dabf7";
    const description = wrapText(item.description, 118, 2);
    return `<rect x="90" y="${y}" width="1020" height="86" rx="14" fill="#10211d" stroke="${color}" stroke-opacity="0.75"/>
    <text x="122" y="${y + 29}" fill="${color}" font-family="ui-monospace,monospace" font-size="12" font-weight="700">${item.primary ? "PRIMARY" : "SECONDARY"}</text>
    <text x="250" y="${y + 29}" fill="#e8fff7" font-family="ui-monospace,monospace" font-size="17" font-weight="700">${escapeXml(shorten(item.file, 88))}</text>
    ${textLines(description, 122, y + 56, 17, 'fill="#9bb8ae" font-family="ui-sans-serif,system-ui,sans-serif" font-size="12"')}`;
  }).join("\n");
  const flowStart = 137 + items.length * 112;
  const flow = primary.executionFlow.slice(0, 8).map((step, index) => `<circle cx="111" cy="${flowStart + index * 28}" r="9" fill="#20c997"/><text x="111" y="${flowStart + 4 + index * 28}" text-anchor="middle" fill="#06100e" font-family="ui-monospace,monospace" font-size="9" font-weight="800">${index + 1}</text><text x="132" y="${flowStart + 4 + index * 28}" fill="#9bb8ae" font-family="ui-monospace,monospace" font-size="12">${escapeXml(shorten(step, 135))}</text>`).join("\n");
  const heading = primary.executionFlow.length > 0
    ? `<text x="90" y="${flowStart - 25}" fill="#20c997" font-family="ui-monospace,monospace" font-size="12" font-weight="700" letter-spacing="1.2">PRIMARY STARTUP FLOW</text>`
    : "";
  return svgShell(width, height, `${repoName} · Entry Points`, `${cards}${heading}${flow}`);
}
